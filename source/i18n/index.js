function clock(ms) {
  const s = Math.floor(ms / 1000);
  const m = Math.floor(s / 60);
  const r = s % 60;
  return `${m}:${String(r).padStart(2, "0")}`;
}
function signedPct(v, d = 2) {
  const s = v >= 0 ? "+" : "";
  return `${s}${(v * 100).toFixed(d)}%`;
}

